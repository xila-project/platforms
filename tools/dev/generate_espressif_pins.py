#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.11"
# ///
"""Generate the per-chip GPIO line tables of `drivers/espressif`.

The tables come from the pin limitations that esp-hal publishes in its chip
metadata (`esp-metadata-generated`). Each chip file lists every bonded GPIO,
except the pins that are never usable as a general-purpose line:

- pins reserved for the SPI flash the chip boots from;
- the USB D-/D+ pins used by USB-Serial-JTAG or USB OTG;
- pins only bonded on some packages (ESP32 GPIO20, ESP32-PICO-V3 only).

Every other limitation becomes a flag, and the board decides which flagged
lines to withhold through `Gpio::new`'s reserved mask.

Usage:
    uv run --script tools/dev/generate_espressif_pins.py <path to esp-metadata-generated-X.Y.Z>
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

CHIPS = {
    "esp32": ("esp32.rs", "ESP32"),
    "esp32c2": ("esp32_c2.rs", "ESP32-C2"),
    "esp32c3": ("esp32_c3.rs", "ESP32-C3"),
    "esp32c5": ("esp32_c5.rs", "ESP32-C5"),
    "esp32c6": ("esp32_c6.rs", "ESP32-C6"),
    "esp32c61": ("esp32_c61.rs", "ESP32-C61"),
    "esp32h2": ("esp32_h2.rs", "ESP32-H2"),
    "esp32p4": ("esp32_p4.rs", "ESP32-P4"),
    "esp32s2": ("esp32_s2.rs", "ESP32-S2"),
    "esp32s3": ("esp32_s3.rs", "ESP32-S3"),
    "esp32s31": ("esp32_s31.rs", "ESP32-S31"),
}

# Limitation text in esp-metadata -> what the generator does with the line.
EXCLUDE = {
    "This pin may be reserved for interfacing with SPI flash.": "SPI flash",
    "These pins may be used to debug the chip using USB.": "USB D-/D+",
    "This pin is only available on ESP32-PICO-V3.": "ESP32-PICO-V3 only",
}
FLAGS = {
    "This pin is a strapping pin, it determines how the chip boots.": "STRAPPING",
    "These pins may be used to debug the chip using an external JTAG debugger.": "JTAG",
    "By default, this pin is used by the UART programming interface.": "CONSOLE",
    "This pin may be reserved for interfacing with SPI PSRAM.": "MODULE_MEMORY",
    "This pin may be reserved for interfacing with Octal SPI flash.": "MODULE_MEMORY",
    "This pin may be reserved for interfacing with Octal SPI PSRAM.": "MODULE_MEMORY",
}
INPUT_ONLY = "This pin can only be used as an input."

# Espressif documents these ESP32-P4 pins as the default UART0 transmit and
# receive pins, but the chip metadata only marks them as strapping pins.
CONSOLE_PINS = {"esp32p4": {37, 38}}

PIN = re.compile(
    r'#\[doc\s*=\s*"GPIO(\d+) peripheral singleton[^"]*"\](.*?)\bGPIO\1\s*<=\s*virtual\(\)',
    re.DOTALL,
)
ITEM = re.compile(r"<li>(.*?)</li>", re.DOTALL)


def parse(path: Path) -> dict[int, list[str]]:
    source = path.read_text()
    start = source.index("macro_rules! for_each_peripheral")
    pins: dict[int, list[str]] = {}
    for match in PIN.finditer(source, start):
        number = int(match.group(1))
        items = [" ".join(item.split()) for item in ITEM.findall(match.group(2))]
        pins.setdefault(number, items)
    return pins


def render(chip: str, title: str, version: str, pins: dict[int, list[str]]) -> str:
    excluded: dict[str, list[int]] = {}
    lines: list[str] = []
    for number in sorted(pins):
        items = pins[number]
        unknown = [i for i in items if i not in EXCLUDE and i not in FLAGS and i != INPUT_ONLY]
        if unknown:
            raise SystemExit(f"{chip} GPIO{number}: unknown limitation {unknown!r}")
        reasons = [EXCLUDE[i] for i in items if i in EXCLUDE]
        if reasons:
            for reason in reasons:
                excluded.setdefault(reason, []).append(number)
            continue
        flags = {FLAGS[i] for i in items if i in FLAGS}
        if number in CONSOLE_PINS.get(chip, ()):
            flags.add("CONSOLE")
        macro = "pin_input_only" if INPUT_ONLY in items else "pin_line"
        if flags:
            joined = ".union(LineFlags::".join(sorted(flags))
            expression = "LineFlags::" + joined + ")" * (len(flags) - 1)
            lines.append(f"    {macro}!({number}, {expression}),")
        else:
            lines.append(f"    {macro}!({number}),")

    def ranges(numbers: list[int]) -> str:
        return ", ".join(f"GPIO{n}" for n in numbers)

    exclusions = "\n".join(
        f"/// - {reason}: {ranges(numbers)}" for reason, numbers in sorted(excluded.items())
    )
    uses = ["use crate::shared::Line;"]
    if any("LineFlags::" in line for line in lines):
        uses.append("use crate::shared::LineFlags;")
    if any("pin_input_only!" in line for line in lines):
        uses.append("use crate::pin_input_only;")
    if any("pin_line!" in line for line in lines):
        uses.append("use crate::pin_line;")
    uses.sort()  # rustfmt's order, so regenerated files pass `cargo fmt --check`

    return (
        "// Generated by tools/dev/generate_espressif_pins.py from\n"
        f"// esp-metadata-generated {version}. Do not edit by hand.\n\n"
        + "\n".join(uses)
        + "\n\n"
        + f"/// GPIO lines of the {title}.\n"
        + "///\n"
        + "/// Every bonded GPIO is listed with its limitations as `LineFlags`; the\n"
        + "/// board withholds the ones it uses through `Gpio::new`'s reserved mask.\n"
        + "/// Not listed:\n"
        + (exclusions + "\n" if exclusions else "/// - nothing\n")
        + "pub static LINES: &[Line] = &[\n"
        + "\n".join(lines)
        + "\n];\n"
    )


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    metadata = Path(sys.argv[1])
    version = metadata.name.removeprefix("esp-metadata-generated-")
    output = Path(__file__).resolve().parents[2] / "drivers/espressif/src/chips"
    for chip, (file, title) in CHIPS.items():
        pins = parse(metadata / "src" / f"_generated_{chip}.rs")
        if not pins:
            raise SystemExit(f"{chip}: no GPIO found")
        (output / file).write_text(render(chip, title, version, pins))
        print(f"{chip}: {len(pins)} GPIOs -> {file}")


if __name__ == "__main__":
    main()
